# graphs/satellite_colors.py

import hashlib
import matplotlib as mpl


# ==========================================================
# COLOR PALETTE
# ==========================================================

COLOR_MAP = mpl.colormaps["tab20"]

COLOR_COUNT = 20


# ==========================================================
# SATELLITE COLOR STORAGE
# ==========================================================

SATELLITE_COLORS = {}


# ==========================================================
# GET SATELLITE COLOR
# ==========================================================

def get_satellite_color(meosar_id):
    """
    Return a consistent color for a MEOSAR satellite.

    The same MEOSAR satellite will always receive the same
    color across every graph generated by the application.
    """

    meosar_id = str(meosar_id)

    if meosar_id not in SATELLITE_COLORS:

        hash_value = hashlib.md5(
            meosar_id.encode("utf-8")
        ).hexdigest()

        index = int(hash_value, 16) % COLOR_COUNT

        SATELLITE_COLORS[meosar_id] = COLOR_MAP(
            index / (COLOR_COUNT - 1)
        )

    return SATELLITE_COLORS[meosar_id]